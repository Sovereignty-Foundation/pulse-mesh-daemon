"""The crate index: every workspace member by tier, with its manifest description."""
import json, subprocess, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
meta = json.loads(subprocess.check_output(['cargo', 'metadata', '--no-deps', '--format-version', '1'], cwd=root))
# each group's path prefixes: the integrated tree's, and the top levels the split repositories put the same crates
# under (the daemon's `dev_ring/`; `tools/`, `examples/`, `plugins/`, `clients/` and `bindings/` beside a workspace)
tiers = [(('pulse/',), '0', 'The canonical primitive'), (('core/',), '1', 'The engine'), (('mesh/',), '2', 'The fabric'),
         (('dev_ring/', 'dev_ring/'), '3', 'The dev ring'), (('rings/enterprise_ring/',), '3', 'The enterprise ring'),
         (('rings/hft_ring/',), '3', 'The HFT ring'), (('rings/robotics_ring/',), '3', 'The robotics ring'),
         (('peripheral/', 'tools/', 'examples/', 'plugins/', 'clients/', 'bindings/'), 'peripheral', 'The peripheral surface')]
rows = {}
for pkg in meta['packages']:
    rel = pathlib.Path(pkg['manifest_path']).parent.relative_to(root).as_posix() + '/'
    for prefixes, tier, _ in tiers:
        if rel.startswith(prefixes):
            status = ((pkg.get('metadata') or {}).get('pulse-mesh') or {}).get('status', '')
            rows.setdefault(prefixes, []).append((pkg['name'], rel.rstrip('/'), (pkg.get('description') or '').replace('|', '\\|'), status))
            break
print('<!-- Generated by scripts/docs/gen-crate-index.py from `cargo metadata`; do not edit by hand. -->')
print('# Crate index\n')
print('<p class="pm-kind"><b>Reference · generated</b> · every workspace crate by tier, with the description its manifest carries</p>\n')
print('A tier depends only on the tiers below it; the peripheral surface depends on all of them and is depended on by none. The description column is each crate\'s `Cargo.toml` description, so this table is exactly what `cargo metadata` reports. The status column is the crate\'s `package.metadata.pulse-mesh.status`: `pre-integration` for a crate the tree ships but does not use yet (ADR-0014), `partial` for one in use some of whose public entry points return a deferred error (ADR-0017), blank for one that is finished and wired in.\n')
for prefixes, tier, title in tiers:
    if prefixes not in rows: continue
    present = ', '.join(f'`{p}`' for p in prefixes if any(path.startswith(p) for _, path, _, _ in rows[prefixes]))
    print(f'## {title} (tier {tier}, {present})\n')
    print('| Crate | Path | Status | Description |\n|---|---|---|---|')
    for name, path, desc, status in sorted(rows[prefixes]):
        print(f'| `{name}` | `{path}` | {status} | {desc} |')
    print()
