# Regenerate every generated reference page. Usage: gen-all.sh [out-dir]  (default: book/src)
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT="${1:-book/src}"
mkdir -p "$OUT/reference" "$OUT/explanation"
# A page a binary prints is generated where the workspace has the binary's
# crate (the daemon's pages are the daemon's alone); the crate index, the
# error catalogue and the decision log every tree has.
members=$(cargo metadata --no-deps --format-version 1 |
  python3 -c 'import json, sys; print(" ".join(p["name"] for p in json.load(sys.stdin)["packages"]))')
has() { case " $members " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }
n=3
if has pms-cli; then cargo run -q --release -p pms-cli -- docs cli-markdown > "$OUT/reference/cli-reference.md"; n=$((n + 1)); fi
if has mesh-hub; then cargo run -q --release -p mesh-hub -- --dump-cli-markdown > "$OUT/reference/daemon-reference.md"; n=$((n + 1)); fi
if has pms-mcp; then cargo run -q --release -p pms-mcp -- --dump-tools-markdown > "$OUT/reference/mcp-tools.md"; n=$((n + 1)); fi
if has pms-cli; then
  # The modules page: the twelve modules and the developer profiles that select them, read through
  # `pms modules ls --json` from the static table in dev_ring/dev-functions/src/core_ops/modules.rs.
  python3 - > "$OUT/reference/modules.md" <<'PY'
import json, re, subprocess, sys
def ls(*args):
    return json.loads(subprocess.check_output(['cargo', 'run', '-q', '--release', '-p', 'pms-cli', '--', 'modules', 'ls', '--json', *args]))
mods = ls()
order = ['hft', 'ai', 'robotics', 'telemetry', 'dev']  # the order pms names them in its help and its errors
unlisted = sorted({p for m in mods for p in m['profiles']} - set(order))
if unlisted:
    sys.exit(f'gen-all: profiles {unlisted} are not in the modules page; add them to its order')
def ring(crate):
    m = re.match(r'(dev|enterprise|hft|robotics)_', crate)
    return f'{m.group(1)}_ring' if m else ''
names = {p: [f'`--for {p}`'] for p in order}
if ls('--for', 'inference') == ls('--for', 'ai'):
    names['ai'].append('`--for inference`')
print('<!-- Generated by scripts/docs/gen-all.sh from `pms modules ls --json`; do not edit by hand. -->')
print('# Modules and developer profiles\n')
print('<p class="pm-kind"><b>Reference · generated</b> · the twelve optimization modules, and the developer profiles that select them</p>\n')
print('A developer profile is a tag that `pms modules ls --for` and `pms doctor --for` take, and that the MCP `modules_list` tool takes as `profile`. It selects modules from the table below and enables nothing: `pms modules ls --for` lists them, and `pms doctor --for` adds a line naming them. An unknown profile makes `pms modules ls` exit 1 and `pms doctor` report a warning. A developer profile is not the profiles repository (`pulse-mesh-profiles`), which holds the enterprise, HFT and robotics rings.\n')
print('The table is static, in `dev_ring/dev-functions/src/core_ops/modules.rs`, and this page is generated from what `pms modules ls --json` prints.\n')
print('## Developer profiles\n')
print('| Profile | Flag | Modules | Rings the modules sit in |\n|---|---|---|---|')
for p in order:
    chosen = [m for m in mods if p in m['profiles']]
    rings = sorted({ring(m['crate_name'].split('::')[0]) for m in chosen} - {''})
    print(f"| `{p}` | {', '.join(names[p])} | {', '.join(m['id'] for m in chosen)} | {', '.join(f'`{r}`' for r in rings)} |")
print('\n## Modules\n')
print('A module is a crate of its own or a module inside one layer of a ring (`crate::module`). The ring column names the ring whose layer holds it, and is blank for a crate of its own.\n')
print('| Module | Crate or module | Ring | What it does | Developer profiles |\n|---|---|---|---|---|')
for m in mods:
    r = ring(m['crate_name'].split('::')[0])
    print(f"| {m['id']} | `{m['crate_name']}` | {f'`{r}`' if r else ''} | {m['summary'].replace('|', chr(92) + '|')} | {', '.join(f'`{p}`' for p in m['profiles'])} |")
PY
  n=$((n + 1))
fi
python3 scripts/docs/gen-crate-index.py > "$OUT/reference/crates.md"
python3 scripts/docs/gen-errors.py > "$OUT/reference/errors.md"
python3 scripts/docs/gen-decisions.py > "$OUT/explanation/decision-log.md"
echo "generated $n pages into $OUT"
