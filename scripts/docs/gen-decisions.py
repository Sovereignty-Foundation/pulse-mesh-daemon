"""The decision log index, from the files under decisions/."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
print('<!-- Generated by scripts/docs/gen-decisions.py from decisions/; do not edit by hand. -->')
print('# Decision log\n')
print('<p class="pm-kind"><b>Explanation · generated</b> · the architectural decision record under `decisions/`, in order, never rewritten</p>\n')
print('Each record states its context, the decision and its consequences, and stays in place when a later record supersedes it. The index below is read from the files; the files are the record.\n')
print('A non-obvious call (where something belongs, why a crate is shaped the way it is, anything a later contributor would otherwise reverse-engineer from a pull request) gets a new record rather than only an explanation in the pull request. Number it one past the highest present, and say in its body which earlier record it supersedes, if any. Numbers are never reused, so a gap is a retired record.\n')
print('| ADR | Title | Status | Date |\n|---|---|---|---|')
for f in sorted(root.glob('decisions/*.md')):
    text = f.read_text()
    title = re.search(r'^# (.+)$', text, re.M).group(1).strip()
    num, _, name = title.partition(' — ')
    status = re.search(r'\*\*Status:\*\*\s*(.+)', text); date = re.search(r'\*\*Date:\*\*\s*(.+)', text)
    # Plain numbers, no links: the files sit under decisions/ beside the book in every repository.
    status_text = re.sub(r'\[([^\]]+)\]\(\d{4}-[^)]+\.md\)', r'\1', status.group(1).strip()) if status else ''
    print(f'| {num} | {name or title} | {status_text} | {date.group(1).strip() if date else ""} |')
print()
