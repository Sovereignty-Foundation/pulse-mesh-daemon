"""The error catalogue: every public error enum in the workspace, variant by variant, with its doc comment.

A line scanner, not a regular expression over whole files: rustfmt's layout puts an enum's
variants exactly four columns deeper than its `pub enum` line, so the variants are the lines
at that indentation and their doc comments are the `///` lines at the same indentation just above."""
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[2]
skip_dirs = {'target', 'book', 'node_modules', '.git'}
enum_line = re.compile(r'^(?P<indent>[ \t]*)pub enum (?P<name>\w*Error\w*)\s*\{\s*$')
variant_line = re.compile(r'^(?P<name>[A-Z]\w*)')


def enums_in(text):
    lines = text.split('\n')
    i = 0
    while i < len(lines):
        m = enum_line.match(lines[i])
        if not m:
            i += 1
            continue
        indent = m.group('indent')
        inner = indent + '    '
        variants = []
        doc = []
        in_attr = False  # a `#[...]` attribute rustfmt wrapped onto several lines
        j = i + 1
        while j < len(lines) and lines[j] != indent + '}':
            line = lines[j]
            if in_attr:
                in_attr = not line.rstrip().endswith(']')
            elif line.startswith(inner) and not line.startswith(inner + ' '):
                s = line[len(inner):]
                if s.startswith('///'):
                    doc.append(s[3:].strip())
                elif s.startswith('#['):
                    in_attr = not s.rstrip().endswith(']')
                else:
                    v = variant_line.match(s)
                    if v:
                        variants.append((v.group('name'), ' '.join(doc).replace('|', '\\|')))
                        doc = []
            j += 1
        yield m.group('name'), variants
        i = j + 1


print("<!-- Generated by scripts/docs/gen-errors.py from the crates' public error enums; do not edit by hand. -->")
print('# Error catalogue\n')
print('<p class="pm-kind"><b>Reference · generated</b> · every public error type in the workspace, variant by variant, with the meaning its documentation states</p>\n')
print('The table is read from the source, so a variant that exists is listed and a variant that is gone disappears. The troubleshooting guide gives remedies for the errors a user meets from the command line.\n')
files = sorted(p for p in root.rglob('*.rs') if not (set(p.parts) & skip_dirs) and 'tests' not in p.parts)
for f in files:
    for name, variants in enums_in(f.read_text()):
        if not variants:
            continue
        rel = f.relative_to(root).as_posix()
        crate = rel.split('/src/')[0]
        print(f'## `{name}` in `{crate}`\n')
        print(f'Defined in `{rel}`.\n')
        print('| Variant | Meaning |\n|---|---|')
        for v, d in variants:
            print(f'| `{v}` | {d} |')
        print()
