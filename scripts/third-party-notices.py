"""third-party-notices.py: write THIRD_PARTY_NOTICES.md for the repository at <repo>.

    third-party-notices.py <repo>

Lists every third-party package the repository's Rust workspaces and harnesses resolve (each Cargo.lock), its
JavaScript lock files (each package-lock.json) and its Python projects (each pyproject.toml) declare, with the license
each package states, and reproduces the license and notice files the Rust crates ship, one copy of each distinct text.
First-party packages (path dependencies and workspace members) are left out. Runs offline from the local cargo cache;
the cut runs it in every repository after resolving the lock files. A crate that ships no license file is listed with
its stated license and marked so; the notices for a binary or package built from a subset are a subset of these.
"""

import hashlib
import json
import pathlib
import subprocess
import sys
import tomllib

SKIP = {'target', 'node_modules', '.git'}
LICENSE_FILE_PREFIXES = ('license', 'licence', 'copying', 'notice', 'unlicense')


def lock_dirs(repo, name):
    for p in sorted(repo.rglob(name)):
        if not SKIP.intersection(p.relative_to(repo).parts):
            yield p.parent


def cargo_packages(repo):
    """{(name, version): {'license', 'files': {filename: text}, 'from': set}} for third-party crates."""
    found = {}
    for d in lock_dirs(repo, 'Cargo.lock'):
        if not (d / 'Cargo.toml').exists():
            continue
        r = subprocess.run(['cargo', 'metadata', '--format-version', '1', '--offline', '--manifest-path', str(d / 'Cargo.toml')],
                           cwd=d, text=True, capture_output=True)
        if r.returncode != 0:
            sys.exit(f'{d.relative_to(repo)}: cargo metadata failed: {r.stderr.strip().splitlines()[-1] if r.stderr.strip() else "no output"}')
        meta = json.loads(r.stdout)
        where = str(d.relative_to(repo)) or '.'
        for pkg in meta['packages']:
            if not pkg.get('source'):  # a path dependency or workspace member: first-party
                continue
            key = (pkg['name'], pkg['version'])
            entry = found.setdefault(key, {'license': pkg.get('license') or '', 'files': {}, 'from': set()})
            entry['from'].add(where)
            root = pathlib.Path(pkg['manifest_path']).parent
            names = [f for f in sorted(root.iterdir()) if f.is_file() and f.name.lower().startswith(LICENSE_FILE_PREFIXES)]
            if pkg.get('license_file'):
                extra = root / pkg['license_file']
                if extra.is_file() and extra not in names:
                    names.append(extra)
            for f in names:
                try:
                    entry['files'][f.name] = f.read_text(encoding='utf-8', errors='replace').strip()
                except OSError:
                    pass
            if not entry['license'] and pkg.get('license_file'):
                entry['license'] = f'see {pkg["license_file"]}'
    return found


def npm_packages(repo):
    found = {}
    for d in lock_dirs(repo, 'package-lock.json'):
        lock = json.loads((d / 'package-lock.json').read_text(encoding='utf-8'))
        where = str(d.relative_to(repo))
        for path, pkg in sorted(lock.get('packages', {}).items()):
            if not path or not path.startswith('node_modules/') or pkg.get('link'):
                continue
            name = path.split('node_modules/')[-1]
            found.setdefault((name, pkg.get('version', '')), {'license': pkg.get('license', 'not stated'), 'from': set()})['from'].add(where)
    return found


def python_requirements(repo):
    found = {}
    for d in lock_dirs(repo, 'pyproject.toml'):
        proj = tomllib.loads((d / 'pyproject.toml').read_text(encoding='utf-8')).get('project', {})
        for req in proj.get('dependencies', []):
            found.setdefault(req, set()).add(str(d.relative_to(repo)))
    return found


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    repo = pathlib.Path(sys.argv[1]).resolve()
    crates, npm, py = cargo_packages(repo), npm_packages(repo), python_requirements(repo)

    out = ['# Third-party notices', '',
           f'This repository is proprietary and licensed under the terms in `LICENSE`. It uses the third-party packages below, '
           f'each under its own license. Those licenses, not this repository\'s, govern the packages; where a license requires its '
           f'text or notices to accompany a copy, they are reproduced here.', '',
           f'{len(crates)} Rust crates, {len(npm)} JavaScript packages and {len(py)} Python requirements. Generated by '
           f'`scripts/third-party-notices.py` from the lock files in this repository.', '',
           '## Rust crates', '', '| Crate | Version | License | Used by |', '|---|---|---|---|']
    for (name, version), e in sorted(crates.items()):
        mark = '' if e['files'] else ' (no license file shipped)'
        out.append(f'| {name} | {version} | {e["license"] or "not stated"}{mark} | {", ".join(sorted(e["from"]))} |')
    if npm:
        out += ['', '## JavaScript packages', '', '| Package | Version | License | Used by |', '|---|---|---|---|']
        for (name, version), e in sorted(npm.items()):
            out.append(f'| {name} | {version} | {e["license"]} | {", ".join(sorted(e["from"]))} |')
    if py:
        out += ['', '## Python requirements', '', 'Declared, not locked; the installed version and its license are the installer\'s.', '',
                '| Requirement | Used by |', '|---|---|']
        for req, where in sorted(py.items()):
            out.append(f'| {req} | {", ".join(sorted(where))} |')

    texts = {}
    for (name, version), e in sorted(crates.items()):
        for fname, text in sorted(e['files'].items()):
            digest = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(digest, {'text': text, 'users': []})['users'].append(f'{name} {version} ({fname})')
    out += ['', '## License and notice texts', '',
            'Each distinct text the crates ship appears once, under the crates that ship it.']
    for _, t in sorted(texts.items(), key=lambda kv: kv[1]['users'][0]):
        out += ['', '### ' + '; '.join(t['users']), '', '```text', t['text'].replace('```', "'''"), '```']
    (repo / 'THIRD_PARTY_NOTICES.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'THIRD_PARTY_NOTICES.md: {len(crates)} crates, {len(npm)} npm packages, {len(py)} Python requirements, {len(texts)} distinct texts')
    return 0


if __name__ == '__main__':
    sys.exit(main())
