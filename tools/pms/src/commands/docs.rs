//! `pms docs` — print the generated reference pages the book carries.

use std::process::ExitCode;

/// `pms docs cli-markdown`: the command tree as Markdown, from the clap
/// definitions that parse the real arguments.
pub(crate) fn run_cli_markdown(cmd: clap::Command) -> anyhow::Result<ExitCode> {
    println!("<!-- Generated by `pms docs cli-markdown` (scripts/docs/gen-all.sh); do not edit by hand. -->");
    println!("# The pms command line\n");
    println!("<p class=\"pm-kind\"><b>Reference · generated</b> · every subcommand and flag of `pms`, printed by the binary itself</p>\n");
    print!("{}", mesh_hub::cli_docs::markdown(&cmd));
    Ok(ExitCode::SUCCESS)
}
